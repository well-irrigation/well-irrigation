#!/bin/sh
# =====================================================================
# ملاحظة ميدانية بسطر واحد — قناة المالك إلى المساعد في جلسة الفحص الحيّة
#
#   sh scripts/note.sh "الشاشة تتجمد عند فتح التقارير"
#   sh scripts/note.sh            ← بلا وسائط: تعرض الملاحظات
#
# تُضاف بطابع وقت إلى `.wi-live/notes.log` داخل المستودع (غير متعقَّب)،
# فلا يحتاج المالك تأليف رسالة لكل ملاحظة. والوصف بالكلمات لا بديل له:
# السجل يقول ما فعله الكود، ولا يقول ما رآه إنسان ولا ما أزعجه.
#
# ولماذا داخل المستودع لا في `/tmp`: `${TMPDIR}` يختلف بين المالك والمساعد،
# فملفٌ يكتبه المالك هناك غير مرئي للمساعد — فتبدو القناة عاملة وهي فارغة.
# =====================================================================

set -u

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
log_dir="$root/.wi-live"
mkdir -p "$log_dir" || exit 2
notes="$log_dir/notes.log"

if [ "$#" -eq 0 ]; then
  # بلا وسائط: تُعرض الملاحظات بدل أن يُكتب سطر فارغ.
  if [ -f "$notes" ]; then
    cat "$notes"
  else
    echo "(لا ملاحظات بعد)"
  fi
  exit 0
fi

printf '[%s] %s\n' "$(date '+%H:%M:%S')" "$*" >> "$notes"
printf 'NOTED=%s\n' "$notes"
