/// مسار ملف الطابور — نقطة واحدة، والسبب جوهري.
///
/// التطبيق والعامل الخلفي عمليتان (isolate) منفصلتان تفتحان **نفس
/// الملف**. لو حسب كلٌّ منهما مسارًا بطريقته، لكتب المستخدم عملياته في
/// ملف ولأرسل العامل من ملف آخر فارغ: طابور لا يُفرَّغ أبدًا، بلا أي
/// رسالة خطأ. لذلك المسار محسوب في مكان واحد ينادِيه الطرفان.
///
/// الملف تحت مجلد قواعد البيانات الخاص بالتطبيق: يُحذف بحذف التطبيق أو
/// بمسح بياناته وحدها، ولا تصله تطبيقات أخرى.
library;

import 'package:path/path.dart' as p;
import 'package:sqflite/sqflite.dart';

/// اسم ملف الطابور. لا يُغيَّر بعد أول إصدار: تغييره يعني هاتفًا فيه
/// عمليات لم تُرسل في ملف لا يقرأه أحد.
const String outboxDatabaseFileName = 'well_irrigation_outbox.db';

/// المسار الكامل لملف الطابور على هذا الجهاز.
Future<String> resolveOutboxDatabasePath() async =>
    p.join(await getDatabasesPath(), outboxDatabaseFileName);
